  pts_trend       VARCHAR(20),
  reb_trend       VARCHAR(20),
  ast_trend       VARCHAR(20),
  min_trend       VARCHAR(20),
  created_at      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UNIQUE(player_id, season, as_of_date)
);

CREATE INDEX IF NOT EXISTS idx_prm_player_id ON player_research_metrics(player_id);
CREATE INDEX IF NOT EXISTS idx_prm_season ON player_research_metrics(season);
CREATE INDEX IF NOT EXISTS idx_prm_player_season ON player_research_metrics(player_id, season, as_of_date DESC);
