  avg_usage_rate  DECIMAL(5,4),
  l3_min          DECIMAL(5,2),
  l3_pts          DECIMAL(5,2),
  l3_reb          DECIMAL(5,2),
  l3_ast          DECIMAL(5,2),
  l3_stl          DECIMAL(5,2),
  l3_blk          DECIMAL(5,2),
  l3_tov          DECIMAL(5,2),
  l3_fg3m         DECIMAL(5,2),
  l5_min          DECIMAL(5,2),
  l5_pts          DECIMAL(5,2),
  l5_reb          DECIMAL(5,2),
  l5_ast          DECIMAL(5,2),
  l5_stl          DECIMAL(5,2),
  l5_blk          DECIMAL(5,2),
  l5_tov          DECIMAL(5,2),
  l5_fg3m         DECIMAL(5,2),
  l10_min         DECIMAL(5,2),
  l10_pts         DECIMAL(5,2),
